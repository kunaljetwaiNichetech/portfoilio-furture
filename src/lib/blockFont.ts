export type BlockArt = { main: string; shadow: string; cols: number; rows: number }

export function blockText(text: string, solid = '█', shade = '▒'): BlockArt {
  const rows = 5
  const grid: boolean[][] = Array.from({ length: rows }, () => [])
  for (const ch of text.toUpperCase()) {
    const glyph = G[ch] ?? G[' ']
    for (let r = 0; r < rows; r++) {
      for (const c of glyph[r]) grid[r].push(c === '#')
      grid[r].push(false)
    }
  }
  const cols = grid[0].length + 1
  const main: string[] = []
  const shadow: string[] = []
  for (let r = 0; r < rows + 1; r++) {
    let m = ''
    let s = ''
    for (let c = 0; c < cols; c++) {
      const on = grid[r]?.[c] ?? false
      const behind = grid[r - 1]?.[c - 1] ?? false
      m += on ? solid : ' '
      s += !on && behind ? shade : ' '
    }
    main.push(m)
    shadow.push(s)
  }
  return { main: main.join('\n'), shadow: shadow.join('\n'), cols, rows: rows + 1 }
}
